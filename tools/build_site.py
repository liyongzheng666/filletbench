"""Build public viewer records from repository-relative fresh run directories.

Never reads or copies reference PDFs/images. Existing supplemental snapshots stay
separate. Local absolute paths are sanitized in the derived public records.
"""
import json,pathlib,hashlib,re,collections,argparse
ROOT=pathlib.Path(__file__).resolve().parents[1];WEB=ROOT/'web'
AUDITS={}
def read(p):return json.loads(pathlib.Path(p).read_text())
def digest(p):return hashlib.sha256(pathlib.Path(p).read_bytes()).hexdigest()
def write(p,d):p.parent.mkdir(parents=True,exist_ok=True);p.write_text(json.dumps(d,ensure_ascii=False,separators=(',',':'),allow_nan=False)+'\n')
def sanitize(x):
    if isinstance(x,dict):return {k:sanitize(v) for k,v in x.items()}
    if isinstance(x,list):return [sanitize(v) for v in x]
    if isinstance(x,str):
        x=x.replace(str(ROOT)+'/', '')
        x=re.sub(r'/Users/[^\s\"\'<>]+',lambda m:'local-dependency:'+pathlib.Path(m[0]).name,x)
        x=re.sub(r'/private/[^\s\"\'<>]+',lambda m:'local-runtime:'+pathlib.Path(m[0]).name,x)
    return x

def mesh(path,raw=None):
    if not path.is_file():return None
    d=read(path);out={k:d[k] for k in ['vertices','triangles','edges','selected_edges','metadata'] if k in d};out['face_ids']=d.get('face_ids',d.get('triangle_face_ids',[]))
    if raw and raw.exists() and not out.get('edges'):
        out['edges']=[e['points'] for e in read(raw).get('geometry',{}).get('edges',[]) if e.get('points')]
    if not out.get('vertices') or not out.get('triangles'):return None
    body=json.dumps(sanitize(out),ensure_ascii=False,separators=(',',':'),allow_nan=False)+'\n';key=hashlib.sha256(body.encode()).hexdigest()[:24];p=WEB/f'data/meshes/{key}.json';p.parent.mkdir(parents=True,exist_ok=True);p.write_text(body);return p.relative_to(WEB).as_posix()

def result(engine,j,run):
    path=run/'summary.json';cmd=f'python bench.py run --engine {engine} --job {j["job_id"]}'
    if not path.exists():return {'status':'not_run','label':'未执行','reason':'没有此固定请求的实际执行证据。','reproduce':cmd,'method':'native_edge_fillet'}
    s=read(path);ex=s.get('execution',{});outcome=s.get('outcome');api=s.get('api_success',ex.get('native_api_success'));raw_result=read(run/'result.json') if (run/'result.json').exists() else {};stats=s.get('result_stats') or raw_result.get('native_stats',{});g=s.get('gates',{})
    mismatch=stats.get('valid') is False or (j['expected_input_kind']=='solid' and (stats.get('manifold_solid') is False or stats.get('solids')==0))
    if outcome in ['adapter_not_ready','blocked_by_policy','blocked','policy_blocked','not_run'] or (not j['runnable_by_selected_edge_runner'] and not s.get('native_call_executed') and not ex.get('native_call_started')):
        status='blocked';label='协议未接入';reason=j.get('blocked_reason') or s.get('reason') or '当前普通边 adapter 无法表达此操作。'
    elif 'crash' in outcome or s.get('process_signal'):
        status='crash';label='原生进程崩溃';reason=f'在 {s.get("raw_phase",s.get("stage","unknown"))} 阶段终止；没有成功结果。'
    elif 'timeout' in outcome:
        status='timeout';label='超时';reason=s.get('reason') or '有界调用未完成。'
    elif api is False or 'failed' in outcome or outcome in ['error','exception','missing_dependency']:
        status='api_failed';label='调用失败';reason=s.get('reason') or f'原始返回值 {ex.get("native_api_raw_status",s.get("api_result"))}；保留实际候选供核对。'
    elif mismatch:
        status='geometry_failed';label='几何不符';reason='API 返回成功，但有效性或预期体/片类型不符。'
    elif api is True or outcome in ['ok','native_candidate']:
        status='candidate_unverified';label='已生成 · 待验';reason='原生普通圆角已有候选；尚未证明原图特殊参数、全局质量和人工外观通过。'
    else:
        status='unverified';label='待核实';reason=s.get('reason') or str(outcome)
    audit=AUDITS.get((engine,j['job_id']))
    if audit and audit.get('summary_sha256')!=digest(path):audit=None
    findings=audit.get('scientific_findings',[]) if audit else []
    if api is True and any(f.get('kind') in ['native_invalid_result','solid_became_open_or_sheet','original_sharp_target_retained'] for f in findings):
        status='geometry_failed';label='几何不符'
        reasons=[]
        if any(f.get('kind')=='native_invalid_result' for f in findings):reasons.append('实际 BREP 有效性检查失败')
        if any(f.get('kind')=='solid_became_open_or_sheet' for f in findings):reasons.append('结果未保持预期闭合实体类型')
        if any(f.get('kind')=='original_sharp_target_retained' for f in findings):reasons.append('独立匹配表明原待圆角边仍完整保留为锐边')
        reason='；'.join(reasons)+'。API 成功不代表目标已完成。'
    dst=WEB/f'data/runs/{engine}/{j["job_id"]}';dst.mkdir(parents=True,exist_ok=True)
    s=sanitize(s);s['publication']={'kind':'derived_sanitized_summary','raw_summary_sha256':digest(path),'full_raw_artifacts':'Generated by reproduce command in local runs; artifact paths below are documentary, not all bundled.'}
    write(dst/'summary.json',s)
    for name in ['selection.json','execution.json','phase.json','process.json']:
        if (run/name).exists():write(dst/name,sanitize(read(run/name)))
    if audit:write(dst/'independent-audit.json',sanitize(audit))
    qm=run/'quality-audit.json'
    if qm.exists():write(dst/'quality-audit.json',sanitize(read(qm)))
    meshpath=mesh(run/'result.mesh.json',run/'result.json');before=mesh(run/'before.mesh.json',run/'before.json')
    return {'status':status,'label':label,'reason':reason,'outcome':outcome,'api_success':api,'raw_status':ex.get('native_api_raw_status',s.get('api_result')),'mesh':meshpath,'before_mesh':before,'summary':(dst/'summary.json').relative_to(WEB).as_posix(),'version':s.get('engine_version'),'binding_version':s.get('binding_version'),'method':'native_edge_fillet','metrics':stats,'reproduce':cmd,'source_sha256':s.get('source_sha256'),'request_sha256':s.get('request_sha256'),'representation':'原解析 BREP' if engine=='occt' else '同源有限 NURBS / 共享拓扑','special_feature_passed':False,'evidence_kind':'fresh_run','independent_findings':findings,'independent_audit':(dst/'independent-audit.json').relative_to(WEB).as_posix() if audit else None,'quality_audit':(dst/'quality-audit.json').relative_to(WEB).as_posix() if qm.exists() else None}

def main():
    p=argparse.ArgumentParser();p.add_argument('--occt-runs',default='runs/fresh-occt');p.add_argument('--smlib-runs',default='runs/fresh-smlib');a=p.parse_args()
    global AUDITS
    if (ROOT/'docs/independent-audit.json').exists():AUDITS={(r['engine'],r['job_id']):r for r in read(ROOT/'docs/independent-audit.json')['rows']}
    corpus=read(ROOT/'data/corpus.json');jobs=[read(p) for p in sorted((ROOT/'data/jobs').glob('*.json'))];supp=read(WEB/'data/supplemental/index.json') if (WEB/'data/supplemental/index.json').exists() else {'cases':{}};counts=collections.Counter();cases=[]
    for row in corpus['cases']:
        n=row['number'];c=read(ROOT/f'data/cases/{n:02d}.json')
        for j in jobs:
            if j['number']!=n:continue
            variant={'id':j['job_id'],'label':f'{j["part_label"]} · R{j["radius_mm"]:g}','radius_mm':j['radius_mm'],'role':j['role'],'note':j['request_note'],'targets':j['targets'],'pairing':'same_source_geometry_and_request_different_representations','input_mesh':None,'special_protocol_verified':False,'source_sha256':j['source_sha256'],'semantic_target':j['semantic_target'],'input_construction_note':'两侧使用同源冻结几何，OCCT 读原解析 BREP；SMLib 从有限 NURBS 与共享拓扑重建。当前只调用普通边圆角。'}
            for engine,folder in [('occt',a.occt_runs),('smlib',a.smlib_runs)]:
                variant[engine]=result(engine,j,ROOT/folder/j['job_id']);counts[engine+':'+variant[engine]['status']]+=1
            variant['input_mesh']=variant['occt'].get('before_mesh') or variant['smlib'].get('before_mesh');c['variants'].append(variant)
        extra=supp.get('cases',{}).get(f'{n:02d}',supp.get('cases',{}).get(str(n),[]))
        c['variants'].extend(extra)
        preferred=next((v['id'] for v in c['variants'] if n==8 and v.get('radius_mm')==18 and v.get('occt',{}).get('mesh')),None)
        c['default_variant']=preferred or next((v['id'] for v in c['variants'] if v.get('smlib',{}).get('mesh')),c['variants'][0]['id'] if c['variants'] else None)
        write(WEB/f'data/cases/{n:02d}.json',c)
        cases.append({**row,'data':f'data/cases/{n:02d}.json','variant_count':len(c['variants']),'default_variant':c['default_variant']})
    summary={'schema_version':1,'project':'FilletBench','repository':'https://github.com/liyongzheng666/filletbench','dataset_tier':'exploratory_reconstruction','counts':{'cases':len(cases),'ordinary_requests':len(jobs),'runnable_requests':sum(j['runnable_by_selected_edge_runner'] for j in jobs),'variants':sum(c['variant_count'] for c in cases),'outcomes':dict(counts)},'cases':cases,'excluded':corpus['excluded'],'overall_accuracy_score':None,'reference_policy':'client-local only; never uploaded'}
    write(WEB/'data/catalog.json',summary);print(json.dumps(summary['counts'],ensure_ascii=False))
if __name__=='__main__':main()
